func emailAddress(value string) (string, error) {
	value = strings.ToLower(strings.TrimSpace(value))
	parsed, err := mail.ParseAddress(value)
	if err != nil || parsed.Address != value || len(value) > 254 {
		return "", ErrInvalid
	}
	return value, nil
}
func name(value string) bool {
	return len(strings.TrimSpace(value)) > 0 && len(value) <= 100 && !strings.ContainsAny(value, "\r\n\x00")
}
func conflict(err error) error {
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == "23505" {
		return ErrConflict
	}
	return err
}
func (s *Service) acquire() bool {
	select {
	case s.slots <- struct{}{}:
		return true
	default:
		return false
	}
}
func (s *Service) release() { <-s.slots }

// Rate stores shared authentication budgets as expiring control-plane session
// metadata. Keys contain only a keyed digest, never a raw IP or email. No unscoped
// Redis keys or additional global tables are introduced.
func (s *Service) Rate(ctx context.Context, purpose, client string, limit int, window time.Duration) error {
	sessionID, err := id()
	if err != nil {
		return err
	}
	var count int
	err = s.pool.QueryRow(ctx, `INSERT INTO identity.sessions(id,kind,token_hash,family_id,expires_at,rate_count) VALUES($1,'rate',$2,$1,$3,1) ON CONFLICT(token_hash) DO UPDATE SET rate_count=CASE WHEN identity.sessions.expires_at<=$4 THEN 1 ELSE identity.sessions.rate_count+1 END, expires_at=CASE WHEN identity.sessions.expires_at<=$4 THEN $3 ELSE identity.sessions.expires_at END RETURNING rate_count`, sessionID, keyedHash(s.key, "rate:"+purpose+":"+client), s.now().Add(window), s.now()).Scan(&count)
	if err != nil {
		return err
	}
	if count > limit {
		return ErrLimited
	}
	return nil
}
func (s *Service) Signup(ctx context.Context, email, password, displayName, workspaceName, oldToken string) (pair, error) {
	var result pair
	email, err := emailAddress(email)
	if err != nil || !name(displayName) || !name(workspaceName) || !validPassword(password) {
		return result, ErrInvalid
	}
	if !s.acquire() {
		return result, ErrLimited
	}
	hash, err := HashPassword(password)
	s.release()
	if err != nil {
		return result, err
	}
	userID, err := id()
	if err != nil {
		return result, err
	}
	workspaceID, err := id()
	if err != nil {
		return result, err
	}
	user := User{ID: userID, Email: email, DisplayName: strings.TrimSpace(displayName)}
	// A new scope is generated by the server, not supplied by the caller. It only
	// becomes the user's active authenticated scope if this entire transaction commits.
	err = database.WithTenant(ctx, s.pool, workspaceID, func(tx database.TenantTx) error {
		if _, err := tx.Exec(ctx, `INSERT INTO identity.users(id,email,display_name) VALUES($1,$2,$3)`, userID, email, user.DisplayName); err != nil {
			return conflict(err)
		}
		if _, err := tx.Exec(ctx, `INSERT INTO identity.credentials(user_id,password_hash) VALUES($1,$2)`, userID, hash); err != nil {
			return err
		}
		if err := s.createWorkspace(ctx, tx, user, strings.TrimSpace(workspaceName)); err != nil {
			return err
		}
		result, err = s.issue(ctx, tx, user, policy.Admin, oldToken, uuid.Nil, time.Time{})
		if err != nil {
			return err
		}
		return events.Write(ctx, tx, workspaceID, userID, "auth.signed_up", events.Payload{After: map[string]string{"user_id": userID.String(), "workspace_id": workspaceID.String()}})
	})
	return result, err
}
func (s *Service) Login(ctx context.Context, email, password, oldToken string) (pair, error) {
	var result pair
	email, err := emailAddress(email)
	if err != nil || len(password) > 256 {
		return result, ErrUnauthenticated
	}
	if !s.acquire() {
		return result, ErrLimited
	}
	defer s.release()
	var user User
	var passwordHash string
	var failed int
	var locked *time.Time
	authenticated := false
	err = s.identityTx(ctx, func(tx pgx.Tx) error {
		err := tx.QueryRow(ctx, `SELECT u.id,u.email,u.display_name,c.password_hash,c.failed_attempts,c.locked_until FROM identity.users u JOIN identity.credentials c ON c.user_id=u.id WHERE u.email=$1 FOR UPDATE OF c`, email).Scan(&user.ID, &user.Email, &user.DisplayName, &passwordHash, &failed, &locked)
		if errors.Is(err, pgx.ErrNoRows) {
			_ = VerifyPassword(s.dummy, password)
			return nil
		}
		if err != nil {
			return err
		}
		matches := VerifyPassword(passwordHash, password)
		if locked != nil && locked.After(s.now()) {
			return nil
		}
		if !matches {
			failed++
			var until *time.Time
			if failed >= 5 {
				expiry := s.now().Add(15 * time.Minute)
				until = &expiry
				failed = 0
			}
			_, err = tx.Exec(ctx, `UPDATE identity.credentials SET failed_attempts=$2,locked_until=$3 WHERE user_id=$1`, user.ID, failed, until)
			return err
		}
		authenticated = true
		_, err = tx.Exec(ctx, `UPDATE identity.credentials SET failed_attempts=0,locked_until=NULL WHERE user_id=$1`, user.ID)
		return err
	})
	if err != nil {
		return result, err
	}
	if !authenticated {
		return result, ErrUnauthenticated
	}
	var workspace uuid.UUID
	if err = s.pool.QueryRow(ctx, `SELECT workspace_id FROM identity.memberships WHERE user_id=$1 ORDER BY created_at,id LIMIT 1`, user.ID).Scan(&workspace); err != nil {
		return result, ErrUnauthenticated
	}
	err = database.WithTenant(ctx, s.pool, workspace, func(tx database.TenantTx) error {
		// Recheck the credential under lock so a concurrent reset cannot issue a
		// fresh session using a password that was just revoked.
		var stillCurrent bool
		if err := tx.QueryRow(ctx, `SELECT password_hash=$2 AND (locked_until IS NULL OR locked_until<=$3) FROM identity.credentials WHERE user_id=$1 FOR SHARE`, user.ID, passwordHash, s.now()).Scan(&stillCurrent); err != nil || !stillCurrent {
			return ErrUnauthenticated
		}
		var role policy.Role
		if err := tx.QueryRow(ctx, `SELECT role FROM app.members WHERE user_id=$1 AND workspace_id=$2 FOR SHARE`, user.ID, workspace).Scan(&role); err != nil {
			return ErrUnauthenticated
		}
		actor := policy.Actor{ID: user.ID.String(), WorkspaceID: workspace.String(), Role: role}
		if !policy.Can(ctx, actor, policy.SessionWrite, policy.Resource{WorkspaceID: workspace.String(), OwnerID: user.ID.String()}) {
			return ErrForbidden
		}
		result, err = s.issue(ctx, tx, user, role, oldToken, uuid.Nil, time.Time{})
		if err != nil {
			return err
		}
		return events.Write(ctx, tx, workspace, user.ID, "auth.login", events.Payload{After: map[string]string{"session_id": result.Session.ID.String()}})
	})
	return result, err
}
func (s *Service) createWorkspace(ctx context.Context, tx database.TenantTx, user User, workspaceName string) error {
	workspace := tx.WorkspaceID()
	if _, err := tx.Exec(ctx, `INSERT INTO app.objects(id,workspace_id,type,created_by) VALUES($1,$1,'workspace',$2)`, workspace, user.ID); err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `INSERT INTO app.workspaces(id,workspace_id,name) VALUES($1,$1,$2)`, workspace, workspaceName); err != nil {
		return err
	}
	if err := s.addMember(ctx, tx, user, policy.Admin); err != nil {
		return err
	}
	consumerID, err := id()
	if err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `INSERT INTO identity.sessions(id,workspace_id,kind,token_hash,family_id,expires_at) VALUES($1,$2,'consumer',$3,$1,$4)`, consumerID, workspace, keyedHash(s.key, "consumer:"+workspace.String()), s.now().Add(24*time.Hour)); err != nil {
		return err
	}
	return events.Write(ctx, tx, workspace, user.ID, "workspace.created", events.Payload{After: map[string]string{"workspace_id": workspace.String()}, Version: 1})
}
func (s *Service) addMember(ctx context.Context, tx database.TenantTx, user User, role policy.Role) error {
	memberID, err := id()
	if err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `INSERT INTO identity.memberships(id,user_id,workspace_id,role) VALUES($1,$2,$3,$4)`, memberID, user.ID, tx.WorkspaceID(), role); err != nil {
		return conflict(err)
	}
	if _, err := tx.Exec(ctx, `INSERT INTO app.objects(id,workspace_id,type,created_by) VALUES($1,$2,'membership',$3)`, memberID, tx.WorkspaceID(), user.ID); err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `INSERT INTO app.members(id,workspace_id,user_id,role,email,display_name) VALUES($1,$2,$3,$4,$5,$6)`, memberID, tx.WorkspaceID(), user.ID, role, user.Email, user.DisplayName); err != nil {
		return err
	}
	return events.Write(ctx, tx, memberID, user.ID, "member.joined", events.Payload{After: map[string]string{"user_id": user.ID.String(), "role": string(role)}, Version: 1})
}
func (s *Service) CreateWorkspace(ctx context.Context, session Session, workspaceName, oldToken string) (pair, error) {
	var result pair
	if !name(workspaceName) {
		return result, ErrInvalid
	}
	if !policy.Can(ctx, session.Actor(), policy.WorkspaceCreate, policy.Resource{WorkspaceID: session.WorkspaceID.String()}) {
		return result, ErrForbidden
	}
	workspace, err := id()
	if err != nil {
		return result, err
	}
	err = database.WithTenant(ctx, s.pool, workspace, func(tx database.TenantTx) error {
		var active bool
		if err := tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM identity.sessions WHERE id=$1 AND user_id=$2 AND revoked_at IS NULL AND expires_at>$3)`, session.ID, session.User.ID, s.now()).Scan(&active); err != nil {
			return err
		}
		if !active {
			return ErrUnauthenticated
		}
		if err := s.createWorkspace(ctx, tx, session.User, strings.TrimSpace(workspaceName)); err != nil {
			return err
		}
		result, err = s.issue(ctx, tx, session.User, policy.Admin, oldToken, uuid.Nil, time.Time{})
		return err
	})
	return result, err
}
